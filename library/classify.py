def _key(s):
    s = s.lower()
    for a, b in (("ы","и"),("і","и"),("ї","и"),("є","е"),("ё","е"),("э","е"),("й","и"),("ь",""),("ъ",""),("’",""),("'",""),("ʼ","")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()

def _ua(name):
    """«Владимир Рудницкий» → «Володимир Рудницький» (приблизно, для спікерів, яких ще немає в базі)"""
    w = name.split()
    w[0] = FIRST.get(w[0], w[0])
    sur = w[-1]
    sur = re.sub(r"(ск|цк|зк)ий$", r"\1ий", sur)
    if re.search(r"(ск|цк|зк)ий$", sur): sur = sur[:-2] + "ий"[:0] + "ьий"[:0] + sur[-2:]   # лишаємо як є
    sur = re.sub(r"(ск|цк|зк)ий$", lambda m: m.group(1) + "ий", sur)
    sur = re.sub(r"([сцз])кий$", r"\1ький", sur)
    w[-1] = sur
    return " ".join(w)

def topics_extra(title):
    low = title.lower()
    return [k for k, rx in RU_TOPICS.items() if any(re.search(r, low) for r in rx)]

def speaker_of(title, text, known):
    """known — список спікерів, які вже відомі з назв («Імʼя Прізвище»)"""
    kk = {}
    for k in known:
        kk.setdefault(_key(k), _ua(k))      # на виході — українська форма
    kk.update({_key(a): b for a, b in ALIAS.items()})
    first_known = {_key(k.split()[0]) for k in known} | {_key(v) for v in FIRST.values()} | {_key(k) for k in FIRST}
    def norm(c):
        c = re.sub(PREFIX, "", c.strip()); w = c.split()
        if not 2 <= len(w) <= 3 or BAD.search(c) or re.search(r"(ович|евич|івна|овна|евна|ична)$", w[-1]) and _key(" ".join(w[:2])) not in kk: return ""
        for cand in (c, " ".join(reversed(w[:2])) if len(w) == 2 else c):
            cw = cand.split(); cw[0] = FIRST.get(cw[0], cw[0]); k = _key(" ".join(cw[:2]))
            if k in kk: return kk[k]
        if _key(w[0]) in first_known or w[0] in FIRST: return _ua(c if len(w) == 2 else " ".join(w[:2]))
        return ""
    cands = []
    m = re.match(rf"^({NAME}(?:\s+{NAME}){{1,2}})\s*[–—-]\s+\S", title)
    if m: cands.append(m.group(1))
    m = re.search(rf"\s[–—-]\s+((?:Пастор\s+)?{NAME}\s+{NAME})\.?$", title)
    if m: cands.append(m.group(1))
    if re.fullmatch(rf"{NAME}(?:\s+{NAME}){{1,2}}", title): cands.append(title)
    m = re.match(rf"^((?:(?:Пастор|Єпископ|Епископ|Священик|Брат)\s+)?{NAME}(?:\s+{NAME}){{1,2}})\s+(?:Церковь|Церква|ц\.|Церкви|церкви|церква|церковь|\(|,|г\.|м\.|www|\d{{2}}\.\d{{2}})", text or "")
    if m: cands.append(m.group(1))
    for c in cands:
        r = norm(c)
        if r: return r
    return ""
